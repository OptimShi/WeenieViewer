using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Threading.Tasks;
using WeenieViewer.Enums;

namespace WeenieViewer.Db.weenie
{
    public class Generator
    {
        public int objectId;
        public float probability;
        public int weenieClassId;
        public float delay;
        public int initCreate;
        public int maxCreate;
        public int whenCreate;
        public int whereCreate;
        public int stackSize;
        public int paletteId;
        public float shade; 
        public uint objCellId;
        public float x;
        public float y;
        public float z;
        public float qw;
        public float qx;
        public float qy;
        public float qz;

        public string objectName;
        public string weenieName;

        public string ToGeneratesString()
        {
            RegenerationType _whenCreate = (RegenerationType)whenCreate;
            RegenLocationType _whereCreate = (RegenLocationType)whereCreate;

            return $"Generate `{weenieName}` ({weenieClassId}) (x{initCreate} up to max of {maxCreate} - Regenerate upon {_whenCreate} - Location to (re)Generate: {_whereCreate}";
        }

        public string ToGeneratedByString()
        {
            return $"Generated by `{objectName}` ({objectId})";
        }

    }

}
